let fruits = ["Apple", "Mango", "Banana", "Cherry"];
const upperfruits = fruits.map((fruits) => fruits.toUpperCase()); // THIS MAP IS TAKING THE ARRAY FRUITS AND WITH HELP OF ARROW 
                                                                  // AND CONVERT FRUITS TO UPPRECASE USING UPPERCASE FUNCTION
console.log(fruits);
console.log(upperfruits);